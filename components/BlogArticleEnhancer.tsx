"use client";
import { usePathname } from "next/navigation";
type Lang = "ro" | "en" | "ru" | "ua";

const labels: Record<Lang, {
  saveTitle: string;
  saveDesc: string;
  saveBtn: string;
  generated: string;
  clinic: string;
}> = {
  ro: {
    saveTitle: "Salvează articolul",
    saveDesc: "Descarcă articolul ca document pentru citire offline.",
    saveBtn: "Descarcă articolul",
    generated: "Document generat de Revimed PLUS+",
    clinic: "Centrul Medical Revimed PLUS+"
  },
  en: {
    saveTitle: "Save article",
    saveDesc: "Download this article as a document for offline reading.",
    saveBtn: "Download article",
    generated: "Document generated by Revimed PLUS+",
    clinic: "Revimed PLUS+ Medical Center"
  },
  ru: {
    saveTitle: "Сохранить статью",
    saveDesc: "Скачайте статью как документ для чтения офлайн.",
    saveBtn: "Скачать статью",
    generated: "Документ создан Revimed PLUS+",
    clinic: "Медицинский центр Revimed PLUS+"
  },
  ua: {
    saveTitle: "Зберегти статтю",
    saveDesc: "Завантажте статтю як документ для читання офлайн.",
    saveBtn: "Завантажити статтю",
    generated: "Документ створено Revimed PLUS+",
    clinic: "Медичний центр Revimed PLUS+"
  }
};

// React owns article markup; no timers, innerHTML replacement or DOM rewriting.
export default function BlogArticleEnhancer() {
 const pathname = usePathname();
 const part = pathname.split("/")[1];
 const lang: Lang = part === "en" || part === "ru" || part === "ua" ? part : "ro";
 const copy = labels[lang];
 function download() {
  const title = document.querySelector("h1")?.textContent || copy.clinic;
  const text = document.querySelector(".blogReadableContent")?.textContent || "";
  const escape = (s: string) => s.replace(/[&<>"]/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;"}[c]!));
  const blob = new Blob([`<html><meta charset="utf-8"><body><h1>${escape(title)}</h1><p>${escape(text)}</p></body></html>`], {type:"application/msword;charset=utf-8"});
  const url = URL.createObjectURL(blob); const a = document.createElement("a");
  a.href = url; a.download = "revimed-article.doc"; a.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
 }
 return <section className="rmShell adminCard"><h2>{copy.saveTitle}</h2><p>{copy.saveDesc}</p><button type="button" onClick={download}>{copy.saveBtn}</button></section>;
}
